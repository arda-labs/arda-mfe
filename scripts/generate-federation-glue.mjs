// Generates the Module Federation glue that must name every remote literally:
// the federation plugin and TypeScript only see `import("<remote>/Routes")`
// when the specifier is a string literal, so these files cannot be computed at
// runtime. The single source is federation.routes.ts (remote names and the
// remotes that expose ./taskForms); this script writes the files below and
// `--check` (run by `bun run check:federation`) fails when they are stale.
//
//   bun run gen:federation            regenerate
//   bun run gen:federation -- --check verify only
import { readFile, writeFile } from "node:fs/promises"
import { join } from "node:path"
import { remoteNames, taskFormRemotes } from "../federation.routes.ts"

const root = join(import.meta.dirname, "..")
const header = "// Generated by scripts/generate-federation-glue.mjs from federation.routes.ts.\n// Do not edit; run `bun run gen:federation`.\n"

const shellRemoteTypes =
  header +
  remoteNames
    .map(
      (name) => `
declare module "${name}/Routes" {
  import type { ComponentType } from "react"

  const Routes: ComponentType & {
    preload?: (pathname?: string) => Promise<void>
  }
  export default Routes
}
`,
    )
    .join("")

const shellRouteModules = `${header}import type { RemoteName } from "../../../federation.routes"

export const remoteRouteModules = {
${remoteNames.map((name) => `  ${name}: () => import("${name}/Routes"),`).join("\n")}
} satisfies Record<RemoteName, () => Promise<unknown>>
`

const workflowRemoteTypes =
  header +
  `// Domain remotes that expose \`./taskForms\` for the workbench form host (P1.6).
// The default export is the registry keyed by server \`formKey\`; \`locales\` lets
// the host register the owner's locale bundle before rendering its form.
` +
  taskFormRemotes
    .map(
      (name) => `
declare module "${name}/taskForms" {
  import type { TaskFormRegistry } from "@workspace/workflow-task"

  const registry: TaskFormRegistry
  export const taskForms: TaskFormRegistry
  export const locales: { preload: (locale?: string) => Promise<void> }
  export default registry
}
`,
    )
    .join("")

const workflowTaskFormModules = `${header}import type { TaskFormModule } from "@workspace/workflow-task"
import type { TaskFormRemoteName } from "../../../../../../federation.routes"

export const taskFormModules = {
${taskFormRemotes.map((name) => `  ${name}: () => import("${name}/taskForms"),`).join("\n")}
} satisfies Record<TaskFormRemoteName, () => Promise<TaskFormModule>>
`

const outputs = {
  "apps/shell/src/remotes.d.ts": shellRemoteTypes,
  "apps/shell/src/remote-route-modules.generated.ts": shellRouteModules,
  "apps/workflow/src/remotes.d.ts": workflowRemoteTypes,
  "apps/workflow/src/features/workbench/components/task-form-modules.generated.ts": workflowTaskFormModules,
}

const check = process.argv.includes("--check")
const stale = []
for (const [path, content] of Object.entries(outputs)) {
  const file = join(root, path)
  let current = null
  try {
    current = (await readFile(file, "utf8")).replace(/\r\n/g, "\n")
  } catch {
    // Missing counts as stale.
  }
  if (current === content) continue
  if (check) stale.push(path)
  else await writeFile(file, content)
}

if (stale.length) {
  console.error(`Federation glue is stale; run \`bun run gen:federation\`:\n  ${stale.join("\n  ")}`)
  process.exit(1)
}
console.log(
  check
    ? `Federation glue up to date (${remoteNames.length} remotes, ${taskFormRemotes.length} task form hosts)`
    : `Federation glue written (${Object.keys(outputs).length} files)`,
)
