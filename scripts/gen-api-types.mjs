// ADR-005: wire types for the backend REST API are generated from the OpenAPI
// documents in arda-be/contracts/openapi, never written by hand.
//
// For each <name>.json this writes packages/api/src/generated/<name>.ts with
// the openapi-typescript output plus one alias per component schema, prefixed
// with the document name: deposit-v1.json schema "Savings" becomes
// `DepositSavings`. Feature api.ts/types.ts files import these aliases and map
// them to view models.
//
//   bun run gen:api-types            regenerate
//   bun run check:api-types          fail when a committed file is stale
//
// The arda-be checkout is read from ARDA_BE_PATH, defaulting to ../arda-be.
import { readdir, readFile, rm, writeFile } from "node:fs/promises"
import { join, resolve } from "node:path"
import { fileURLToPath } from "node:url"
import openapiTS, { astToString } from "openapi-typescript"

const root = resolve(fileURLToPath(new URL("..", import.meta.url)))
const backend = resolve(root, process.env.ARDA_BE_PATH ?? "../arda-be")
const sourceDir = join(backend, "contracts", "openapi")
const outDir = join(root, "packages", "api", "src", "generated")
const check = process.argv.includes("--check")

export function aliasPrefix(file) {
  const base = file.replace(/\.json$/, "").replace(/-v\d+$/, "")
  return base
    .split(/[-_]/)
    .filter(Boolean)
    .map((part) => part[0].toUpperCase() + part.slice(1))
    .join("")
}

async function render(file) {
  const document = JSON.parse(await readFile(join(sourceDir, file), "utf8"))
  const ast = await openapiTS(document, { alphabetize: true })
  const body = astToString(ast).trimEnd()
  const prefix = aliasPrefix(file)
  const names = Object.keys(document.components?.schemas ?? {}).sort()
  const aliases = names.map((name) => `export type ${prefix}${name} = components["schemas"]["${name}"]`)
  return [
    "/**",
    ` * Generated by scripts/gen-api-types.mjs from arda-be/contracts/openapi/${file}.`,
    " * Do not edit by hand: change the OpenAPI document in arda-be, then run",
    " * `bun run gen:api-types`.",
    " */",
    "",
    body,
    "",
    `// Named aliases for components.schemas, prefixed with "${prefix}".`,
    ...aliases,
    "",
  ].join("\n")
}

let sources
try {
  sources = (await readdir(sourceDir)).filter((name) => name.endsWith(".json")).sort()
} catch {
  console.error(`OpenAPI documents not found in ${sourceDir}; set ARDA_BE_PATH to the arda-be checkout`)
  process.exit(1)
}
if (sources.length === 0) {
  console.error(`No OpenAPI documents in ${sourceDir}`)
  process.exit(1)
}

const expected = new Set(sources.map((file) => file.replace(/\.json$/, ".ts")))
const existing = (await readdir(outDir).catch(() => [])).filter((name) => name.endsWith(".ts"))
const problems = []

for (const file of sources) {
  const target = join(outDir, file.replace(/\.json$/, ".ts"))
  const content = await render(file)
  if (check) {
    const current = (await readFile(target, "utf8").catch(() => null))?.replaceAll("\r\n", "\n")
    if (current !== content) problems.push(`${target} is stale`)
  } else {
    await writeFile(target, content)
  }
}
for (const name of existing) {
  if (expected.has(name)) continue
  if (check) problems.push(`${join(outDir, name)} has no OpenAPI document`)
  else await rm(join(outDir, name))
}

if (problems.length) {
  console.error(problems.join("\n"))
  console.error("\nRun `bun run gen:api-types` against the arda-be checkout that holds the contract change.")
  process.exit(1)
}
console.log(
  `${check ? "API types up to date" : "Generated API types"}: ${sources.length} document(s) from ${sourceDir}`,
)
